export function supplyLine(product) {
  if (product.supply) return product.supply
  if (product.card) return product.card
  return [product.solids, product.carrier].filter(Boolean).join(' ')
}

export function productsFor(familyId, applicationId) {
  return PRODUCTS.filter(
    (product) => product.family === familyId && product.applications.includes(applicationId),
  )
}

export function productById(id) {
  return PRODUCTS.find((product) => product.id === id) || null
}
